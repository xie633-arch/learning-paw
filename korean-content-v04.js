const loadProgress = () => {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return {};
    const state = JSON.parse(raw);
    return state?.lessonProgress && typeof state.lessonProgress === 'object' ? state.lessonProgress : {};
  } catch {
    return {};
  }
};

const curriculum = curricula.korean;
const progress = loadProgress();
const steps = curriculum?.steps || [];
const currentLesson = steps.find(step => !progress[step.id]) || null;
const unlockedLessons = new Set(
  steps
    .filter(step => progress[step.id])
    .map(step => step.id),
);
if (currentLesson) unlockedLessons.add(currentLesson.id);

